// Builds the code that runs inside a WebView into a string constant.
//
// The adapter used to inject `fn.toString()`. Hermes doesn't keep function
// source (it returns `function f(a0) { [bytecode] }`), so on a device the page
// got no code. This bundles src/adapters/webview-page.ts with esbuild instead
// and writes the result to src/adapters/webview-page.generated.ts, which is
// committed so `bun test <file>` works without a build; `bun run generate`
// (part of typecheck, test and build) refreshes it, and a test fails when it is
// stale.
import { writeFileSync } from 'node:fs'
import { build } from 'esbuild'

export async function bundle() {
  const { outputFiles } = await build({
    entryPoints: ['src/adapters/webview-page.ts'],
    bundle: true,
    write: false,
    format: 'iife',
    globalName: '__agentBridgePage',
    target: 'es2020',
    platform: 'neutral',
    minify: true,
    legalComments: 'none',
  })
  // One expression evaluating to { bootMain, pageMain }.
  return `(function(){${outputFiles[0].text.trim()};return __agentBridgePage})()`
}

export const render = (code) =>
  `// Generated by scripts/generate-webview-page.mjs from webview-page.ts. Do not edit.\nexport const PAGE_BUNDLE: string = ${JSON.stringify(code)}\n`

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync('src/adapters/webview-page.generated.ts', render(await bundle()))
}
